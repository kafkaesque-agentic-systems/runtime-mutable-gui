"""The gate record: which whole-repository command has passed on which tree (design D-32).

Purpose: a tree is tested once. Every run of a gate command is one line in
`docs/ledger/phase-NN-gate.md`, with the commit it ran on. From those lines this
module answers whether a command is green on the tree as it stands now, so the
runner does not repeat a run that can say nothing new, and so the gate before a
merge runs exactly what the tree to be merged has not passed.
Dependencies: gitutil.
Side effects: `append` adds one line to the record file; nothing else writes.
"""
from __future__ import annotations

import fnmatch
import hashlib
import re
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple

from . import gitutil as git

# The runner's own files. No gate command reads them, so a commit that changes nothing else
# leaves every result standing: a ticket's status line, a ledger row, the brief, the handoff.
RUNNER_FILES = (".tickets/", "docs/ledger/", "docs/qa/reviews/", "HANDOFF.md")
QUICK, SEAM = "quick", "seam"
GREEN = "green"
HEADER = ("# Gate record: phase {phase:02d}\n\n"
          "One line per run of a gate command, appended by the runner (`devpipe run`, `devpipe gate`). A command is\n"
          "green on a tree when its newest line here is green and every file changed since that commit is one no\n"
          "gate reads: the runner's own files, and what the project names in `phase_gate_ignore`. Such a command is\n"
          "not run again. `devpipe gate --check` prints what this tree still owes. Do not edit this file.\n\n"
          "| When | Commit | Key | Result | Seconds | Log | Command |\n"
          "|---|---|---|---|---|---|---|\n")


def record_name(phase: int) -> str:
    """The record's path inside the repository."""
    return f"docs/ledger/phase-{phase:02d}-gate.md"


def key(command: str) -> str:
    """What a line is found by. A command reworded in the configuration is another command."""
    return hashlib.sha1(command.encode("utf-8")).hexdigest()[:10]


def commands(config: Dict[str, Any]) -> List[Tuple[str, str]]:
    """Every gate command with its kind, in the order a gate runs them: the quick ones first."""
    quick = [(str(command), QUICK) for command in config.get("phase_gate") or []]
    return quick + [(str(command), SEAM) for command in config.get("seam_gate") or []]


def append(root: Path, phase: int, when: str, commit: str, command: str, code: int, stale: str,
           seconds: int, log: str) -> None:
    """Add one run to the record, creating the file with its header."""
    path = root / record_name(phase)
    path.parent.mkdir(parents=True, exist_ok=True)
    if not path.exists():
        path.write_text(HEADER.format(phase=phase), encoding="utf-8")
    if code != 0:
        result = f"red (exit {code})"
    elif stale:
        result = "did not run (reused: " + stale.replace("|", "/").strip() + ")"
    else:
        result = GREEN
    # The command comes last, so a pipe inside it cannot shift the cells that are read back.
    with path.open("a", encoding="utf-8") as handle:
        handle.write(f"| {when} | {commit} | {key(command)} | {result} | {seconds} | `{log}` | `{command}` |\n")


def read(root: Path, phase: int, at: str = "") -> str:
    """The record's text: from the working tree, or as the commit `at` holds it."""
    if at:
        return git.git(root, "show", f"{at}:{record_name(phase)}", check=False)
    path = root / record_name(phase)
    return path.read_text(encoding="utf-8") if path.is_file() else ""


def rows(text: str) -> List[Dict[str, str]]:
    """The record's lines, oldest first: {commit, key, result}."""
    found = []
    for line in text.splitlines():
        cells = line.split(" | ", 6)
        if len(cells) == 7 and re.fullmatch(r"[0-9a-f]{7,40}", cells[1].strip()) and re.fullmatch(r"[0-9a-f]{10}", cells[2].strip()):
            found.append({"commit": cells[1].strip(), "key": cells[2].strip(), "result": cells[3].strip()})
    return found


def unseen(path: str, config: Dict[str, Any]) -> bool:
    """True when no gate command reads `path`: a runner file, or one the project's `phase_gate_ignore` names."""
    if any(path == own or (own.endswith("/") and path.startswith(own)) for own in RUNNER_FILES):
        return True
    for pattern in config.get("phase_gate_ignore") or []:
        pattern = str(pattern)
        if (pattern.endswith("/") and path.startswith(pattern)) or fnmatch.fnmatch(path, pattern):
            return True
    return False


def state(root: Path, config: Dict[str, Any], command: str, text: str, at: str = "") -> Dict[str, Any]:
    """Where `command` stands on a tree, by the record `text`.

    The tree is the commit `at`, or the working tree when `at` is empty (uncommitted
    changes then count as changes). Returns `green_at`: the commit of the run that still
    holds for this tree, or '' when the command is owed; `ever`: whether it has passed in
    this phase at all; `changed`: the files a gate may read that differ since its last
    green run; `why`: the reason it is owed, in words.
    """
    mine = [row for row in rows(text) if row["key"] == key(command)]
    ever = any(row["result"] == GREEN for row in mine)
    owed: Dict[str, Any] = {"green_at": "", "ever": ever, "changed": [], "since": ""}
    if not mine:
        return {**owed, "why": "it has not run in this phase"}
    if mine[-1]["result"] != GREEN:
        return {**owed, "why": f"its last run was not green ({mine[-1]['result']})"}
    commit = mine[-1]["commit"]
    files: Optional[List[str]] = git.changed_between(root, commit, at or "HEAD")
    if files is None:
        return {**owed, "why": f"the commit it passed on ({commit[:8]}) is not in this repository"}
    if not at:
        files = sorted(set(files) | set(git.changed_files(root)))
    counted = [path for path in files if not unseen(path, config)]
    if counted:
        return {**owed, "changed": counted, "since": commit,
                "why": f"{len(counted)} file{'s' if len(counted) != 1 else ''} changed since it passed on {commit[:8]}"}
    return {"green_at": commit, "ever": True, "changed": [], "since": commit, "why": ""}


def standing(root: Path, config: Dict[str, Any], phase: int, at: str = "") -> List[Dict[str, Any]]:
    """Every gate command with its kind and its state on the tree: what `devpipe gate --check` prints."""
    text = read(root, phase, at)
    return [{"command": command, "kind": kind, **state(root, config, command, text, at)}
            for command, kind in commands(config)]
